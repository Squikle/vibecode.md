"""The vault's merge (`tools/vault/vault_merge.py`, called by `vaultify.py`): a file you edited gets the new docs by a
3-way `git merge-file` against the bytes vaultify last wrote (`.vaultify/base/`); a conflict leaves your file alone, parks
the new version in `.vaultify/conflicts/`, exits 1, writes `vault-alert.json` next to the vault and puts a warning on the
hub; `--resolve` takes a hand-merged file back; an edited file with no base is a conflict; an old vault seeds its base.

python -I -X utf8 -m unittest discover -s tools/vault/tests      (stdlib only; needs git on PATH)"""
import io, json, shutil, sys, tempfile, unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import vaultify  # noqa: E402

FILES = {
    "AGENTS.md": "# Agents\n\nRead the docs.\n",
    "docs/BACKLOG.md": "# Backlog\n\n| # | Batch | Status | What |\n|---|---|---|---|\n| 1 | `alpha` The first | open | builds a thing |\n",
    "docs/MERGES.md": "# Merges\n\n### 2026-01-02 10:00 · alpha · 185a7f18\n\n- **What:** a thing\n",
}
DOC = "# Handover\n\n## 3. The plan\n\n" + "".join(f"Line {i}.\n\n" for i in range(1, 9))
NOTE = "docs/HANDOVER.md"
WARN = "> [!warning] 1 note didn't get the new docs: [[docs/HANDOVER]]"


def put(root, files):
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(text.encode("utf-8"))
    return root


def call(*args):
    out = io.StringIO()
    with redirect_stdout(out), redirect_stderr(io.StringIO()):
        code = vaultify.main(list(args))
    return code, json.loads(out.getvalue().strip().splitlines()[-1])


def edit(p, old, new):
    p.write_bytes(p.read_bytes().replace(old.encode(), new.encode()))


@unittest.skipIf(shutil.which("git") is None, "git is not installed")
class Merge(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.src, self.vault = put(self.tmp / "src", {**FILES, NOTE: DOC}), self.tmp / "vault"
        self.note, self.parked = self.vault / NOTE, self.vault / ".vaultify/conflicts" / NOTE
        self.alert = self.tmp / "vault-alert.json"

    def build(self):
        return call("--src", str(self.src), "--vault", str(self.vault))

    def resolve(self, given):
        return call("--vault", str(self.vault), "--resolve", given)

    def manifest(self):
        return json.loads((self.vault / ".vaultify/manifest.json").read_text(encoding="utf-8"))

    def hub(self):
        return (self.vault / "index.md").read_text(encoding="utf-8")

    def warnings(self):
        return [l for l in self.hub().splitlines() if l.startswith("> [!warning]")]

    def test_a_clean_merge_keeps_your_line_and_gets_the_new_one(self):
        self.build()
        self.assertEqual((self.vault / ".vaultify/base" / NOTE).read_bytes(), self.note.read_bytes())   # every write has a base
        edit(self.note, "Line 2.", "Line 2, your words.")
        edit(self.src / NOTE, "Line 7.", "Line 7, the new docs.")
        code, out = self.build()
        text = self.note.read_text(encoding="utf-8")
        self.assertEqual((code, out["merged"], out["conflicts"], out["written"]), (0, 1, 0, 0))
        self.assertNotIn("kept_edited", out)
        self.assertTrue("Line 2, your words." in text and "Line 7, the new docs." in text and "<<<<<<<" not in text)
        base = (self.vault / ".vaultify/base" / NOTE).read_text(encoding="utf-8")
        self.assertTrue("Line 7, the new docs." in base and "your words" not in base)   # base := the new generated bytes
        self.assertEqual(self.manifest()[NOTE], vaultify.h12(self.note.read_bytes()))   # manifest := the merged hash
        self.assertFalse(self.alert.exists())
        self.assertEqual(self.warnings(), [])
        code, out = self.build()                                                        # nothing new: your file stays
        self.assertEqual((code, out["merged"], out["written"], out["conflicts"]), (0, 0, 0, 0))
        self.assertEqual(self.note.read_text(encoding="utf-8"), text)
        edit(self.src / NOTE, "Line 5.", "Line 5, newer still.")                        # the next change merges again
        code, out = self.build()
        text = self.note.read_text(encoding="utf-8")
        self.assertEqual(out["merged"], 1)
        self.assertTrue("your words" in text and "newer still" in text and "Line 7, the new docs." in text)

    def test_a_crlf_file_merges_and_stays_crlf(self):
        self.build()
        self.note.write_bytes(self.note.read_bytes().replace(b"Line 2.", b"Line 2, yours.").replace(b"\n", b"\r\n"))
        edit(self.src / NOTE, "Line 7.", "Line 7, new.")
        code, out = self.build()
        data = self.note.read_bytes()
        self.assertEqual((code, out["merged"], out["conflicts"]), (0, 1, 0))
        self.assertTrue(b"Line 2, yours.\r\n" in data and b"Line 7, new.\r\n" in data)
        self.assertNotIn(b"\n", data.replace(b"\r\n", b""))

    def test_a_conflict_parks_the_new_version_and_alerts_then_resolve_takes_it_back(self):
        self.build()
        edit(self.note, "Line 4.", "Line 4, your way.")
        mine = self.note.read_bytes()
        edit(self.src / NOTE, "Line 4.", "Line 4, the docs' way.")
        code, out = self.build()
        self.assertEqual((code, out["conflicts"], out["merged"]), (1, 1, 0))
        self.assertEqual(self.note.read_bytes(), mine)
        self.assertIn("Line 4, the docs' way.", self.parked.read_text(encoding="utf-8"))
        alert = json.loads(self.alert.read_text(encoding="utf-8"))
        self.assertEqual((alert["conflicts"], alert["misses"], alert["rev"]), ([NOTE], [], "src"))
        self.assertTrue(alert["time"])
        self.assertEqual(self.warnings(), [WARN])
        self.assertLess(self.hub().index("[!warning]"), self.hub().index("Built "))     # at the top of the hub
        self.assertEqual(self.build()[0], 1)                                            # still a conflict, still yours
        self.assertEqual(self.note.read_bytes(), mine)
        self.note.write_bytes(self.parked.read_bytes().replace(b"Line 1.", b"Line 1, merged by hand."))
        code, res = self.resolve(NOTE)
        self.assertEqual((code, res["resolved"], res["conflicts"]), (0, NOTE, 0))
        self.assertFalse(self.parked.exists() or self.alert.exists())
        self.assertEqual(self.manifest()[NOTE], vaultify.h12(self.note.read_bytes()))
        code, out = self.build()
        self.assertEqual((code, out["conflicts"], out["merged"]), (0, 0, 0))
        self.assertIn("merged by hand", self.note.read_text(encoding="utf-8"))
        self.assertEqual(self.warnings(), [])

    def test_resolve_takes_an_absolute_path_and_refuses_what_is_no_conflict(self):
        self.build()
        edit(self.note, "Line 4.", "Line 4, your way.")
        edit(self.src / NOTE, "Line 4.", "Line 4, the docs' way.")
        self.build()
        mine, before = self.note.read_bytes(), (self.manifest(), self.alert.read_bytes())
        for bad in ("docs/NOPE.md", str(self.tmp / "elsewhere.md"), ".vaultify/manifest.json", "../src/" + NOTE):
            self.assertEqual(self.resolve(bad)[0], 2, bad)                               # refused, nothing changed
            self.assertEqual((self.manifest(), self.alert.read_bytes(), self.note.read_bytes(), self.parked.is_file()),
                             (*before, mine, True), bad)
        code, res = self.resolve(str(self.note))                                        # pasted as the hook prints it
        self.assertEqual((code, res["resolved"]), (0, NOTE))
        self.assertTrue(self.note.read_bytes() == mine and not self.parked.exists())    # your file is never deleted
        code, out = self.build()
        self.assertEqual((code, out["conflicts"]), (0, 0))
        self.assertEqual(self.note.read_bytes(), mine)

    def test_an_edited_file_with_no_base_is_a_conflict_never_kept_silently(self):
        foreign = self.vault / "AGENTS.md"                                              # your file at a generated path
        foreign.parent.mkdir(parents=True)
        foreign.write_bytes(b"mine\n")
        code, out = self.build()
        self.assertEqual((code, out["conflicts"]), (1, 1))
        self.assertEqual(foreign.read_bytes(), b"mine\n")
        self.assertTrue((self.vault / ".vaultify/conflicts/AGENTS.md").is_file())
        edit(self.note, "Line 2.", "Line 2, yours.")
        (self.vault / ".vaultify/base" / NOTE).unlink()                                 # an edit and no base: no merge
        edit(self.src / NOTE, "Line 7.", "Line 7, new.")
        code, out = self.build()
        alert = json.loads(self.alert.read_text(encoding="utf-8"))
        self.assertEqual((code, sorted(alert["conflicts"])), (1, ["AGENTS.md", NOTE]))
        self.assertIn("Line 2, yours.", self.note.read_text(encoding="utf-8"))

    def test_an_old_vault_seeds_its_base_from_the_files_it_wrote(self):
        self.build()
        shutil.rmtree(self.vault / ".vaultify/base")                                    # built before the base copies
        code, out = self.build()
        base = self.vault / ".vaultify/base"
        seeded = {p.relative_to(base).as_posix() for p in base.rglob("*") if p.is_file()}
        self.assertEqual((code, out["written"], out["conflicts"]), (0, 0, 0))
        self.assertEqual(seeded, set(self.manifest()))
        edit(self.note, "Line 2.", "Line 2, yours.")
        edit(self.src / NOTE, "Line 7.", "Line 7, new.")
        code, out = self.build()
        self.assertEqual((code, out["merged"]), (0, 1))
        self.assertIn("Line 2, yours.", self.note.read_text(encoding="utf-8"))

    def test_a_miss_alone_alerts_and_a_clean_build_deletes_the_alert(self):
        merges = FILES["docs/MERGES.md"]
        (self.src / "docs/MERGES.md").write_bytes(merges.replace("· alpha · 185a7f18", "alpha 185a7f18").encode())
        code, out = self.build()
        self.assertTrue(code == 1 and out["misses"] >= 1)
        self.assertTrue(json.loads(self.alert.read_text(encoding="utf-8"))["misses"])
        warn = [l for l in self.hub().splitlines() if l.startswith("> ") and "miss" in l]
        self.assertEqual(len(warn), 1)                                                  # one line, its count said once
        self.assertTrue(warn[0].startswith("> [!warning]"))
        (self.src / "docs/MERGES.md").write_bytes(merges.encode())
        code, out = self.build()
        self.assertEqual((code, out["misses"], self.alert.exists()), (0, 0, False))
        self.assertEqual(self.warnings(), [])

    def test_a_vanished_note_with_your_edits_is_a_conflict_until_resolved(self):
        self.build()
        edit(self.note, "Line 2.", "Line 2, yours.")
        (self.src / NOTE).unlink()
        code, out = self.build()
        self.assertEqual((code, out["conflicts"], out["deleted"]), (1, 1, 0))
        self.assertTrue(self.note.is_file())
        self.assertEqual(self.warnings(), [WARN])                                       # the hub counts it as the alert does
        self.assertEqual(self.resolve(NOTE)[0], 0)
        self.assertNotIn(NOTE, self.manifest())
        code, out = self.build()
        self.assertEqual((code, out["conflicts"]), (0, 0))
        self.assertTrue(self.note.is_file())                                            # your own file now: never deleted


if __name__ == "__main__":
    unittest.main()
