"""The vault's `mesh/` (`vaultify.mesh`): the knowledge map of the same rev, written by `tools/kmap/kmap.py export --rev`
after the build; it runs in the git hook, so a hang ends at MESH_TIMEOUT and an error is one word in the JSON line,
never the build's exit.

python -I -X utf8 -m unittest discover -s tools/vault/tests      (stdlib only; needs git on PATH)"""
import io, json, os, shutil, subprocess, sys, tempfile, unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import vaultify  # noqa: E402
from test_vault_merge import FILES, put  # noqa: E402


def call(*args):
    out = io.StringIO()
    with redirect_stdout(out), redirect_stderr(io.StringIO()):
        code = vaultify.main(list(args))
    return code, json.loads(out.getvalue().strip().splitlines()[-1])


@unittest.skipIf(shutil.which("git") is None, "git is not installed")
class Mesh(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def test_a_mesh_that_hangs_or_fails_never_fails_the_build(self):
        src = put(self.tmp / "src", FILES)
        for body, said in (("import time; time.sleep(30)", "error: TimeoutExpired"),
                           ("import sys; sys.exit(3)", "error: exit 3")):
            with self.subTest(said=said):
                tool = self.tmp / "kmap.py"
                tool.write_text(body + "\n", encoding="utf-8")
                with mock.patch.object(vaultify, "KMAP", tool), mock.patch.object(vaultify, "MESH_TIMEOUT", 1):
                    code, out = call("--src", str(src), "--vault", str(self.tmp / "v"), "--mesh", "on")
                self.assertEqual((code, out["mesh"], out["misses"]), (0, said, 0), out)

    def test_mesh_off_and_src_write_no_mesh(self):
        src = put(self.tmp / "src", FILES)
        for args in ((), ("--mesh", "off")):
            with self.subTest(args=args):
                code, out = call("--src", str(src), "--vault", str(self.tmp / "v"), *args)
                self.assertNotIn("mesh", out)
                self.assertFalse((self.tmp / "v" / "mesh").exists())

    def test_the_map_of_the_same_rev_lands_in_mesh(self):
        repo = put(self.tmp / "repo", FILES)
        env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        for args in (["init", "-q", "-b", "main"], ["add", "-A"],
                     ["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "docs"]):
            subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, env=env, timeout=60)
        code, out = call("--repo", str(repo), "--vault", str(self.tmp / "v"))
        self.assertEqual(code, 0, out)
        self.assertTrue(out["mesh"]["written"] > 0 and out["mesh"]["seconds"] > 0, out)
        hub = (self.tmp / "v" / "mesh" / "index.md").read_text(encoding="utf-8")
        self.assertTrue(hub.startswith(f"> generated by kmap at `{out['rev']}`"), hub[:120])
