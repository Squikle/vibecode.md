"""The role registry's CLI: every role's mode, model, effort, budget and value metric live in
`tools/work/roles.json`, and everything that names them is generated from it, so nothing is edited twice.

python -I -X utf8 tools/work/roles.py show [--no-db]          one screen: each role, its mode, model, budget, spend
python -I -X utf8 tools/work/roles.py may <role> [--asked]    exit 0 (may spawn) or 1 with the reason: the role is
    off, or on-request without --asked (the owner or the product lead asked for it); the coordinator runs it before
    every spawn and asks the owner on a 1. A spent week's budget: with `budget_mode` `warn` (until `warn_until`, when
    set) it prints `over budget: <role> $X of $Y/week`, logs it to the main tree's
    `.work/telemetry/budget.log` and exits 0; with `block` it exits 1
python -I -X utf8 tools/work/roles.py budget warn|block [--until YYYY-MM-DD]   switches that mode
python -I -X utf8 tools/work/roles.py set <role> key=value ...  edits the registry, then regenerates; keys: mode
    (on|on-request|off), model (provider/id), effort, when, budget.run, budget.week, value.<n>.threshold
python -I -X utf8 tools/work/roles.py gen      writes what the registry drives: `.opencode/agents/<role>.md`
    (model, tools, permissions), `tools/work/helper.md` and the `model:` line of each command it lists
python -I -X utf8 tools/work/roles.py check    exit 1 on any drift between the registry and those files
A role is in this checkout when one of its `briefs` is (none listed: always); gen and check skip the rest.

Spend is this week's (Monday 00:00 local; only the requests made since then), this project's sessions only, paid API $
and a subscription's tokens at list prices apart (tools/work/role_data.py `week_spend`).
"""
import json
import pathlib
import re
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))  # `python -I` leaves it off
import role_data  # noqa: E402

ROOT = HERE.parents[1]
REGISTRY = HERE / "roles.json"
MODES = ("on", "on-request", "off")
HEADER = "# generated by tools/work/roles.py gen from tools/work/roles.json: edit there, then gen"


def load(path=REGISTRY):
    return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))


def save(reg, path=REGISTRY):
    pathlib.Path(path).write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def rule(action, resource, effect, why=""):
    line = f"  - {{action: {json.dumps(action)}, resource: {json.dumps(resource)}, effect: {effect}}}"
    return line + (f"  # {why}" if why else "")


def git_rules(verbs, why, effect="deny"):
    """Each verb as a session types it, `git <v> ...` and `git -C <path> <v> ...`, each plain and with the text the
    scanner puts before a git command (`* git ...`: measured, `shell_note`). Anchored at `git`, so `digit` never hits."""
    forms = ("git {v} *", "git {v}", "* git {v} *", "* git {v}",
             "git -C * {v} *", "git -C * {v}", "* git -C * {v} *", "* git -C * {v}")
    pats = [f.format(v=v) for v in verbs for f in forms]
    return [rule("shell", p, effect, why if i == 0 else "") for i, p in enumerate(pats)]


def word_rules(words, effect="deny"):
    """A command word as a whole word (each subcommand of a chain is checked alone: measured): `<w> *`, `<w>`, and
    with the text the scanner puts before an `.exe` such as `git` or `rg` (`* <w> *`, `* <w>`); so `del` refuses
    `del x` but not `rg -n storeModel`."""
    out = []
    for w in words:
        word, why = (w, "") if isinstance(w, str) else w
        out += [rule("shell", f, effect, why if i == 0 else "")
                for i, f in enumerate((f"{word} *", word, f"* {word} *", f"* {word}"))]
    return out


def agent_rules(reg, name, a):
    rules = [rule(act, "*", "deny", why) for act, why in reg["common_deny"]]
    if not a.get("websearch", False):
        rules.append(rule("websearch", "*", "deny", "outside facts come from a role with websearch"))
    if not a.get("webfetch", True):
        rules.append(rule("webfetch", "*", "deny"))
    if not a.get("question", False):
        rules += [rule(act, res, eff, why) for act, res, eff, why in reg["unattended"]]
    sub = a.get("subagent", [])
    rules.append(rule("subagent", "*", "deny", a.get("subagent_why", "")))
    rules += [rule("subagent", s, "allow", "hand a big read to a cheaper model" if s == "helper" else "")
              for s in sub]
    edit, why = a.get("edit", "any"), a.get("edit_why", "")
    if edit == "none":
        rules.append(rule("edit", "*", "deny", why))
    elif isinstance(edit, dict) and "only" in edit:
        rules += [rule("edit", "*", "deny", why)] + [rule("edit", p, "allow") for p in edit["only"]]
        rules.append(rule("edit", "*..*", "deny", "no climbing out of an allowed folder"))
    elif isinstance(edit, dict):
        rules += [rule("edit", p, "deny", why if i == 0 else "") for i, p in enumerate(edit["deny"])]
    if a.get("shell_allow"):  # an allowlist: the docs advise it over deny patterns for a read-only role
        rules.append(rule("shell", "*", "deny", "an allowlist: only these commands"))
        rules += git_rules(a.get("git_allow", []), "", "allow")
        rules += word_rules(a["shell_allow"], "allow")
    rules += git_rules(a.get("git_deny", []), a.get("git_why", ""))
    rules += word_rules(a.get("word_deny", []))
    rules += [rule("shell", pat, "deny", why) for pat, why in a.get("shell_deny", [])]  # operators only
    prot = reg.get("protect", {})
    if name not in prot.get("may_edit", []):  # last, so it wins over an `only` allow such as `*.md`
        rules += [rule("edit", p, "deny", prot.get("_doc", "") if i == 0 else "") for i, p in enumerate(prot["edit"])]
        rules += word_rules(prot["shell"])
    return rules


def body_of(reg, a):
    b = a.get("body", [])
    return reg["helper_block"] if b == "helper_block" else b


def agent_file(reg, name, r):
    a = r["agent"]
    lines = ["---", HEADER, f"description: {json.dumps(a['description'])}", f"mode: {a['mode']}",
             f"model: {model_line(r)}", "permissions:"] + agent_rules(reg, name, a) + ["---", ""]
    body = reg.get("body_common", []) + body_of(reg, a)  # the shared part first: every role gets it
    return "\n".join(lines + body + ([""] if body else []))


def helper_doc(reg):
    return "\n".join(["<!-- generated by tools/work/roles.py gen from roles.json `helper_block`: edit there -->",
                      ""] + reg["helper_block"] + [""])


def model_line(r):
    """The model as opencode takes it: `provider/id`, plus `#<effort>` when the registry sets one."""
    return r["model"] + (f"#{r['effort']}" if r.get("effort") else "")


def short(r):
    return model_line(r).split("/", 1)[-1]


def with_command_model(text, r):
    return re.sub(r"(?m)^model: .*$", lambda _: f"model: {model_line(r)}", text, count=1)


def present(root, r):
    """A role is in this checkout when one of its `briefs` is (a solo checkout has no coordinator); none: always."""
    return not r.get("briefs") or any((root / b).is_file() for b in r["briefs"])


def expected(reg, root=ROOT):
    """{path: text} of everything the registry drives, as it should be."""
    want = {root / "tools" / "work" / "helper.md": helper_doc(reg)}
    agents = root / ".opencode" / "agents"
    for name, r in reg["roles"].items():
        if not present(root, r):
            continue
        if r["agent"].get("file"):
            want[agents / f"{name}.md"] = agent_file(reg, name, r)
        for c in r.get("commands", []):
            p = root / ".opencode" / "commands" / f"{c}.md"
            if p in want or p.is_file():  # a command this checkout's setup did not ship is not drift
                want[p] = with_command_model(want.get(p) or p.read_text(encoding="utf-8"), r)
    return want


def drift(reg, root=ROOT):
    bad = [str(p.relative_to(root)).replace("\\", "/") for p, t in expected(reg, root).items()
           if not p.is_file() or p.read_text(encoding="utf-8") != t]
    agents = root / ".opencode" / "agents"
    known = {f"{n}.md" for n, r in reg["roles"].items() if r["agent"].get("file") and present(root, r)}
    bad += [f".opencode/agents/{p.name} (not in the registry)" for p in agents.glob("*.md") if p.name not in known]
    return bad


def gen(reg, root=ROOT):
    for p, t in expected(reg, root).items():
        if not p.is_file() or p.read_text(encoding="utf-8") != t:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(t, encoding="utf-8", newline="\n")
            print("wrote", str(p.relative_to(root)).replace("\\", "/"))
    return 0


def parse_value(v):
    try:
        return float(v) if "." in v else int(v)
    except ValueError:
        return v


def set_keys(reg, role, pairs):
    r = reg["roles"].get(role)
    if r is None:
        raise SystemExit(f"roles: no role {role!r} (roles.py show)")
    for pair in pairs:
        key, eq, val = pair.partition("=")
        if not eq:
            raise SystemExit(f"roles: {pair!r}: want key=value")
        if key == "mode" and val not in MODES:
            raise SystemExit(f"roles: mode must be one of {', '.join(MODES)}")
        if key == "model" and "/" not in val:
            raise SystemExit("roles: model is provider/id, e.g. anthropic/claude-opus-5-5")
        node, parts = r, key.split(".")
        if parts[0] not in ("mode", "model", "effort", "when", "budget", "value"):
            raise SystemExit(f"roles: {key}: not a key set can change")
        for k in parts[:-1]:
            node = node[int(k)] if isinstance(node, list) else node.setdefault(k, {})
        last = parts[-1]
        if isinstance(node, list):
            node[int(last)] = parse_value(val)
        else:
            node[last] = parse_value(val) if parts[0] in ("budget", "value") else val
    return reg


def spend_now(db_path=None):
    """{role: {"runs", "api", "list"}} this week (this project's sessions only, role_data.week_spend), or None without a
    database."""
    try:
        db = role_data.connect(db_path)
    except SystemExit:
        return None
    return role_data.week_spend(db)


def show(reg, spend):
    rows = ["| Role | Mode | Model | $/run | $/week | Runs | API $ | Subscription at list $ | When |",
            "|---|---|---|---:|---:|---:|---:|---:|---|"]
    for name, r in reg["roles"].items():
        s = (spend or {}).get(name, {"runs": 0, "api": 0.0, "list": 0.0})
        week = "- | - | -" if spend is None else f"{s['runs']} | {s['api']:.0f} | {s['list']:.0f}"
        rows.append(f"| {name} | {r['mode']} | {short(r)} | {r['budget']['run']:g} | {r['budget']['week']:g} | {week} | "
                    f"{r['when'][:50]} |")
    return "\n".join(rows + ["", f"Budgets: {reg.get('budget_mode', 'block')} until {reg.get('warn_until', '-')} "
                             "(warn: an overspend is printed and logged, never refused)."])


def budget_log(line, root=ROOT):
    """Appends an overspend to the main tree's `.work/telemetry/budget.log` (machine-local)."""
    p = role_data.main_work(root) / "telemetry" / "budget.log"
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a", encoding="utf-8", newline="\n") as f:
        f.write(f"{time.strftime('%Y-%m-%d %H:%M')} {line}\n")


def may(reg, role, asked, spend, log=budget_log):
    r = reg["roles"].get(role)
    if r is None:
        return 2, f"no role {role!r} in tools/work/roles.json"
    if r["mode"] == "off":
        return 1, f"{role} is off (roles.py set {role} mode=on to turn it on)"
    if r["mode"] == "on-request" and not asked:
        return 1, f"{role} is on-request: spawn it only when the owner or the product lead asked (then pass --asked)"
    if spend is None:
        return 0, f"{role} may run (no database: its budget was not checked)"
    s = spend.get(role, {"runs": 0, "api": 0.0, "list": 0.0})
    usd, cap = s["api"] + s["list"], r["budget"]["week"]
    if usd >= cap:
        line = f"over budget: {role} ${usd:.2f} of ${cap:g}/week (API ${s['api']:.2f}, list ${s['list']:.2f}, {s['runs']} runs)"
        if reg.get("budget_mode", "block") == "block":
            return 1, line + ": ask the owner before another"
        log(line)
        late = time.strftime("%Y-%m-%d") > reg.get("warn_until", "9999")
        return 0, line + (" (warn only; the warn period is over: propose caps)" if late else " (warn only)")
    return 0, f"{role} may run: ${usd:.2f} of ${cap:g} this week, {s['runs']} runs, ~${r['budget']['run']:g} a run"


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    db = None
    if "--db" in argv:
        i = argv.index("--db")
        db = argv[i + 1]
        del argv[i:i + 2]
    reg_path = REGISTRY
    if "--registry" in argv:
        i = argv.index("--registry")
        reg_path = pathlib.Path(argv[i + 1])
        del argv[i:i + 2]
    root = reg_path.resolve().parents[2] if reg_path != REGISTRY else ROOT
    if not argv or argv[0] not in ("show", "may", "set", "gen", "check", "budget"):
        print(__doc__)
        return 2
    reg = load(reg_path)
    cmd, rest = argv[0], argv[1:]
    if cmd == "gen":
        return gen(reg, root)
    if cmd == "check":
        bad = drift(reg, root)
        print("\n".join(f"drift: {b} (roles.py gen)" for b in bad) or "roles: the files match the registry")
        return 1 if bad else 0
    if cmd == "budget":
        if not rest or rest[0] not in ("warn", "block"):
            raise SystemExit("roles: budget warn|block [--until YYYY-MM-DD]")
        reg["budget_mode"] = rest[0]
        if "--until" in rest:
            reg["warn_until"] = rest[rest.index("--until") + 1]
        save(reg, reg_path)
        print(f"roles: budgets {reg['budget_mode']} (until {reg.get('warn_until', '-')})")
        return 0
    if cmd == "set":
        if len(rest) < 2:
            raise SystemExit("roles: set <role> key=value ...")
        save(set_keys(reg, rest[0], rest[1:]), reg_path)
        return gen(reg, root)
    if cmd == "show":
        print(show(reg, None if "--no-db" in rest else spend_now(db)))
        return 0
    if not rest:
        raise SystemExit("roles: may <role> [--asked]")
    code, why = may(reg, rest[0], "--asked" in rest, spend_now(db), lambda line: budget_log(line, root))
    print(why)
    return code


if __name__ == "__main__":
    sys.exit(main())
