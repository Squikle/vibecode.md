"""The knowledge map's other commands: `impact`, `check` (with the golden queries of `docs/kmap/golden.md`), `stats`,
and `export` (Obsidian notes, all regenerated). `miss` is a self-report candidate (`kmap_found`)."""
import collections
import json
import re
import time
from pathlib import Path

from kmap_parse import HUB_MIN, REVERSE, TICK
from kmap_query import describe, flow, resolve, refuse, short

NOTE_KINDS = ("mod", "spec", "area")
REV = re.compile(r"^(?:rev: \w+|> generated by kmap at `\w+`)", re.M)


def cmd_impact(m, a):
    state, ids = resolve(m, a.topic)
    if state != "ok":
        return refuse(state, a.topic, ids)
    nid = ids[0]
    inbound = collections.defaultdict(set)
    for s, t, d, w, conf, ev in m.edges:
        if d == nid:
            inbound[REVERSE.get(t, t)].add(s)
        elif s == nid and t in ("tested-by", "co-changes", "same-files-as", "shares-ui", "conflicts"):
            inbound[t].add(d)
    print(describe(m, nid, 120))
    for label in sorted(inbound, key=lambda k: (-len(inbound[k]), k)):
        items = sorted(inbound[label])
        print(f" {label} ({len(items)}): " + ", ".join(short(m, x) for x in items[:a.budget]) +
              (f" +{len(items) - a.budget}" if len(items) > a.budget else ""))
    if not inbound:
        print(" nothing links to it")
    return 0


def golden(root, m):
    """`docs/kmap/golden.md` lines `` - `topic` has `a` `b`; not `c` `` -> red lines (top 20 at depth 2)."""
    reds = []
    path = root / "docs" / "kmap" / "golden.md"
    if not path.is_file():
        return reds
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.lstrip().startswith(("- `", "* `")):
            continue
        if line.rstrip().endswith("(git)") and m.meta.get("git") == "no":
            continue   # it needs git's links; a map built from the files alone cannot hold it
        where = f"docs/kmap/golden.md:{number}"
        if " via " in line and " has " not in line:
            reds += golden_via(m, line, where)
            continue
        head, _, rest = line.partition(" has ")
        must, _, never = rest.partition(" not ")
        if not rest:
            head, _, never = line.partition(" not ")
        topic = TICK.findall(head)
        if not topic:
            continue
        state, ids = resolve(m, topic[0])
        if state != "ok":
            reds.append(f"golden: {where} topic `{topic[0]}` is {state}")
            continue
        top = {n for n, _ in flow(m, ids, 2)[0][:20]}
        for want, tokens in ((True, TICK.findall(must)), (False, TICK.findall(never))):
            for tok in tokens:
                st, got = resolve(m, tok)
                if st != "ok":
                    reds.append(f"golden: {where} `{tok}` is {st}")
                elif (got[0] in top) != want:
                    reds.append(f"golden: {where} `{topic[0]}` {'misses' if want else 'reaches'} `{tok}` in its top 20")
    return reds


def golden_via(m, line, where):
    """`` - `topic` via `<link>` `a` `b` ``: each is in the topic's top 20 and its strongest link is that one (a real
    `Depends on` must outrank a mention, so cutting the link turns the line red)."""
    head, _, rest = line.partition(" via ")
    topic, toks = TICK.findall(head), TICK.findall(rest)
    if not topic or len(toks) < 2:
        return [f"golden: {where} wants `topic` via `link` `id`..."]
    state, ids = resolve(m, topic[0])
    if state != "ok":
        return [f"golden: {where} topic `{topic[0]}` is {state}"]
    ranked, via, _ = flow(m, ids, 2)
    top, reds = {n for n, _ in ranked[:20]}, []
    for tok in toks[1:]:
        st, got = resolve(m, tok)
        if st != "ok":
            reds.append(f"golden: {where} `{tok}` is {st}")
        elif got[0] not in top or via[got[0]][1] != toks[0] or via[got[0]][0] not in ids:
            how = via[got[0]][1] if got[0] in via else "nothing"
            reds.append(f"golden: {where} `{topic[0]}` reaches `{tok}` via `{how}`, not `{toks[0]}`")
    return reds


def check_lines(root, m):
    """(reds, warns): dangling ids, bad link types, seeds that match nothing, failed golden queries; hubs, binds to
    missing files, open specs in no module, modules with no member."""
    reds = [t for level, t in m.issues if level == "red"] + golden(root, m)
    warns = [t for level, t in m.issues if level == "warn"]
    degs = sorted(m.deg.values())
    if degs:
        cut = max(HUB_MIN, degs[min(len(degs) - 1, int(len(degs) * 0.99))])
        warns += [f"hub: {short(m, n)} has {d} links (damped in every answer; split it, or keep it as a hub)"
                  for n, d in sorted(m.deg.items(), key=lambda kv: -kv[1]) if d > cut][:10]
    mods = sorted(n for n in m.nodes if n.startswith("mod:"))
    if mods:
        member = {o for mod in mods for o, t, label, *_ in m.adj[mod] if label == "has"}
        warns += [f"no module: {short(m, n)}" for n, x in sorted(m.nodes.items())
                  if x["kind"] == "spec" and x["path"] and n not in member
                  and not x["status"].startswith(("done", "merged"))][:20]
        warns += [f"empty module: {short(m, mod)} has no member" for mod in mods
                  if not any(label == "has" for _, t, label, *_ in m.adj[mod])]
    return reds, warns


def cmd_check(root, m, a):
    reds, warns = check_lines(root, m)
    for r in reds:
        print("RED  " + r)
    for w in warns:
        print("WARN " + w)
    print(f"kmap check: {len(reds)} red, {len(warns)} warn ({len(m.nodes)} nodes, {len(m.edges)} links, "
          f"built in {m.meta.get('seconds', '?')} s, git {m.meta.get('git', '?')})")
    return 1 if reds else 0


def cmd_stats(m, a):
    kinds = collections.Counter(n["kind"] for n in m.nodes.values())
    types = collections.Counter(t for _, t, *_ in m.edges)
    hubs = sorted(m.deg.items(), key=lambda kv: -kv[1])[:8]
    if a.json:
        print(json.dumps({"nodes": dict(kinds), "edges": dict(types), "hubs": hubs, "seconds": m.meta.get("seconds")}))
    else:
        print(f"nodes {len(m.nodes)}: " + " ".join(f"{k}={v}" for k, v in sorted(kinds.items())))
        print(f"links {len(m.edges)}: " + " ".join(f"{k}={v}" for k, v in sorted(types.items())))
        print("hubs: " + ", ".join(f"{short(m, n)} {d}" for n, d in hubs) + f"; built in {m.meta.get('seconds')} s")
    return 0


def generated(sha, source=""):
    return (f"> generated by kmap at `{sha[:8]}`; edit the source" + (f" (`{source}`)" if source else "")
            + ", not this note")


def note_of(m, nid, n, sha):
    kind, key = nid.split(":", 1)
    links, files = [], []
    for o, t, label, w, conf in sorted(m.adj[nid], key=lambda e: (-e[3], e[0])):
        ok, okey = o.split(":", 1)
        mark = {"CURATED": " (curated)", "FOUND": " (found)"}.get(conf, "")
        if ok in NOTE_KINDS:
            links.append(f"- {label} [[mesh/{ok}/{okey.replace('/', '__')}|{okey}]]{mark}")
        elif ok == "file" and len(files) < 40:
            files.append(f"- {label} `{okey}`{mark}")
    return "\n".join(["---", f"kind: {kind}", f"status: {json.dumps(n['status'])}", f"source: {json.dumps(n['path'] or '')}",
                      f"rev: {sha[:8]}", "---", generated(sha, n["path"] or ""), "", f"# {key}", "", n["l0"], "",
                      "## Links", *(sorted(set(links)) or ["- none"]), "", "## Files", *(files or ["- none"]), ""])


def cmd_export(m, a, sha):
    """Every note regenerated from the map at `sha`: one written only when more than
    its `rev` changed, a note of a node that is gone deleted; an edit made in the vault is overwritten."""
    t0 = time.time()
    out = Path(a.vault).resolve() / "mesh"
    out.mkdir(parents=True, exist_ok=True)
    (out / ".kmap-export.json").unlink(missing_ok=True)       # phase 1's hashes of kept notes: nothing is kept now
    done, want = collections.Counter(), set()
    index = [f"> generated by kmap at `{sha[:8]}`; edit the sources in git, not these notes: each is regenerated after "
             "every merge, and one whose node is gone is deleted.", "", "# The knowledge map", ""]
    for nid, n in sorted(m.nodes.items()):
        kind, key = nid.split(":", 1)
        if kind in NOTE_KINDS:
            rel = f"{kind}/{key.replace('/', '__')}.md"
            index.append(f"- [[mesh/{rel[:-3]}|{key}]] ({kind})")
            want.add(rel)
            done[put(out, rel, note_of(m, nid, n, sha))] += 1
    want.add("index.md")
    done[put(out, "index.md", "\n".join(index) + "\n")] += 1
    for p in sorted(out.rglob("*.md")):
        if p.relative_to(out).as_posix() not in want:
            p.unlink()
            done["deleted"] += 1
    print(f"export: {done['written']} notes written, {done['same']} unchanged, {done['deleted']} deleted at "
          f"{sha[:8]} in {time.time() - t0:.2f} s ({out})")
    return 0


def put(out, rel, body):
    """One note, written when it changed beyond its `rev` and the sha of its first line; a path that would leave
    `mesh/` (a key with `..` or `\\`) is refused."""
    target = out / rel
    if not target.resolve().is_relative_to(out.resolve()):
        print(f"kmap: export skipped {rel!r}: it resolves outside {out}")
        return "outside"
    if target.is_file() and REV.sub("", target.read_text(encoding="utf-8", errors="replace")) == REV.sub("", body):
        return "same"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(body, encoding="utf-8", newline="\n")
    return "written"